// Command argocd-cm renders config/argocd/lua into the argocd-cm ConfigMap
// patch (config/argocd/argocd-cm-patch.yaml) so the Lua scripts stay
// editable and testable as plain files.
//
//	go run ./hack/argocd-cm
package main

import (
	"fmt"
	"os"
	"path/filepath"
	"slices"
	"strings"

	"sigs.k8s.io/yaml"
)

const (
	luaDir = "config/argocd/lua"
	outTS  = "config/argocd/argocd-cm-patch.yaml"

	healthKey  = "resource.customizations.health.infra.argocd.io_Terraform"
	actionsKey = "resource.customizations.actions.infra.argocd.io_Terraform"
)

type definition struct {
	Name      string `json:"name"`
	ActionLua string `json:"action.lua"`
}

type actions struct {
	DiscoveryLua string       `json:"discovery.lua"`
	Definitions  []definition `json:"definitions"`
}

func main() {
	if err := run(); err != nil {
		fmt.Fprintln(os.Stderr, "error:", err)
		os.Exit(1)
	}
}

func run() error {
	health, err := os.ReadFile(filepath.Join(luaDir, "health.lua"))
	if err != nil {
		return err
	}
	discovery, err := os.ReadFile(filepath.Join(luaDir, "actions", "discovery.lua"))
	if err != nil {
		return err
	}
	entries, err := os.ReadDir(filepath.Join(luaDir, "actions"))
	if err != nil {
		return err
	}
	acts := actions{DiscoveryLua: string(discovery)}
	for _, e := range entries {
		if !e.IsDir() {
			continue
		}
		lua, err := os.ReadFile(filepath.Join(luaDir, "actions", e.Name(), "action.lua"))
		if err != nil {
			return err
		}
		acts.Definitions = append(acts.Definitions, definition{Name: e.Name(), ActionLua: string(lua)})
	}
	slices.SortFunc(acts.Definitions, func(a, b definition) int { return strings.Compare(a.Name, b.Name) })
	actionsYAML, err := yaml.Marshal(acts)
	if err != nil {
		return err
	}

	cm := map[string]any{
		"apiVersion": "v1",
		"kind":       "ConfigMap",
		"metadata": map[string]any{
			"name":      "argocd-cm",
			"namespace": "argocd",
			"labels":    map[string]string{"app.kubernetes.io/part-of": "argocd"},
		},
		"data": map[string]string{
			healthKey:  string(health),
			actionsKey: string(actionsYAML),
		},
	}
	out, err := yaml.Marshal(cm)
	if err != nil {
		return err
	}
	header := strings.Join([]string{
		"# Code generated by hack/argocd-cm from config/argocd/lua. DO NOT EDIT.",
		"#",
		"# Merge into your Argo CD configuration, e.g.:",
		"#   kubectl patch configmap argocd-cm -n argocd --type merge --patch-file config/argocd/argocd-cm-patch.yaml",
		"",
	}, "\n")
	return os.WriteFile(outTS, append([]byte(header), out...), 0o644)
}
